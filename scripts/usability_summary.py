"""Summarise real usability sessions: docs/usability/sessions.csv → docs/usability/results.md.

Reads only rows that have data (a row with just a participant id and order is a planned session).
Writes the generated block between the markers in results.md and leaves everything else (the
moderator's notes, "Top issues and what we changed") untouched. Never invents values: a blank cell
stays blank and is left out of the medians, and with no sessions the gates read PENDING.

    python scripts/usability_summary.py            # update results.md
    python scripts/usability_summary.py --check    # print only; exit 1 if results.md is stale

Round 3 gate (README): SUS mean >= 70 AND reviewers catch more seeded issues with Errata (B) than
manually (A): median B found > median A found, with more participants better in B than worse.
"""

from __future__ import annotations

import argparse
import csv
import statistics
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CSV_PATH = ROOT / "docs" / "usability" / "sessions.csv"
RESULTS_PATH = ROOT / "docs" / "usability" / "results.md"
BEGIN = "<!-- usability_summary:begin (generated by scripts/usability_summary.py; don't edit) -->"
END = "<!-- usability_summary:end -->"

ISSUES = 4  # seeded issues per caption (tasks.md)
SUS_TARGET = 70.0
TASKS = ("t1", "t2", "t3", "t4")
TASK_VALUES = {"Y": "completed", "H": "with help", "N": "not completed"}


class SessionError(ValueError):
    pass


@dataclass
class Session:
    pid: str
    order: str
    a_time: float | None = None
    a_found: int | None = None
    a_wrong: int | None = None
    b_time: float | None = None
    b_found: int | None = None
    b_wrong: int | None = None
    b_ids_correct: int | None = None
    tasks: dict[str, str] = field(default_factory=dict)
    sus: list[int] | None = None

    @property
    def has_data(self) -> bool:
        return any(
            v is not None for v in (self.a_time, self.a_found, self.b_time, self.b_found, self.sus)
        ) or bool(self.tasks)

    @property
    def sus_score(self) -> float | None:
        return sus_score(self.sus) if self.sus else None


def sus_score(answers: list[int]) -> float:
    """Standard SUS: odd items (answer - 1), even items (5 - answer), sum x 2.5 → 0-100."""
    if len(answers) != 10 or any(a not in (1, 2, 3, 4, 5) for a in answers):
        raise SessionError("SUS needs ten answers, each 1-5")
    total = sum((a - 1) if i % 2 == 0 else (5 - a) for i, a in enumerate(answers))
    return total * 2.5


def _num(row: dict[str, str], key: str, pid: str, lo: float, hi: float) -> float | None:
    raw = (row.get(key) or "").strip()
    if not raw:
        return None
    try:
        v = float(raw)
    except ValueError as exc:
        raise SessionError(f"{pid}: {key} must be a number, got {raw!r}") from exc
    if not lo <= v <= hi:
        raise SessionError(f"{pid}: {key} must be between {lo:g} and {hi:g}, got {raw}")
    return v


def _int(row: dict[str, str], key: str, pid: str, lo: int, hi: int) -> int | None:
    v = _num(row, key, pid, lo, hi)
    if v is not None and v != int(v):
        raise SessionError(f"{pid}: {key} must be a whole number")
    return None if v is None else int(v)


def parse(rows: list[dict[str, str]]) -> list[Session]:
    out: list[Session] = []
    for row in rows:
        pid = (row.get("participant") or "").strip()
        if not pid:
            continue
        order = (row.get("order") or "").strip().upper()
        if order not in ("AB", "BA", ""):
            raise SessionError(f"{pid}: order must be AB or BA")
        s = Session(pid=pid, order=order)
        s.a_time = _num(row, "a_time_s", pid, 0, 7200)
        s.a_found = _int(row, "a_found", pid, 0, ISSUES)
        s.a_wrong = _int(row, "a_wrong", pid, 0, 50)
        s.b_time = _num(row, "b_time_s", pid, 0, 7200)
        s.b_found = _int(row, "b_found", pid, 0, ISSUES)
        s.b_wrong = _int(row, "b_wrong", pid, 0, 50)
        s.b_ids_correct = _int(row, "b_ids_correct", pid, 0, ISSUES)
        for t in TASKS:
            v = (row.get(t) or "").strip().upper()
            if v and v not in TASK_VALUES:
                raise SessionError(f"{pid}: {t} must be Y, H or N")
            if v:
                s.tasks[t] = v
        answers = [(row.get(f"sus_q{i}") or "").strip() for i in range(1, 11)]
        if any(answers):
            if not all(answers):
                raise SessionError(f"{pid}: SUS is partly filled; fill all ten or none")
            try:
                s.sus = [int(a) for a in answers]
            except ValueError as exc:
                raise SessionError(f"{pid}: SUS answers must be 1-5") from exc
            sus_score(s.sus)  # validates
        if s.has_data and not s.order:
            raise SessionError(f"{pid}: has results but no order (AB or BA)")
        out.append(s)
    return out


def _median(values: list[float]) -> float | None:
    return statistics.median(values) if values else None


def _fmt(v: float | None, unit: str = "", digits: int = 1) -> str:
    if v is None:
        return ""
    text = f"{v:.{digits}f}".rstrip("0").rstrip(".") if digits else f"{v:.0f}"
    return text + unit


@dataclass
class Summary:
    n: int
    ab_pairs: int
    a_time: float | None
    b_time: float | None
    a_found: float | None
    b_found: float | None
    a_wrong: float | None
    b_wrong: float | None
    b_ids: float | None
    better: int
    same: int
    worse: int
    sus_n: int
    sus_mean: float | None
    sus_sd: float | None
    sus_median: float | None
    sus_min: float | None
    sus_max: float | None
    found_gate: str
    sus_gate: str


def summarise(sessions: list[Session]) -> Summary:
    done = [s for s in sessions if s.has_data]
    pairs = [s for s in done if s.a_found is not None and s.b_found is not None]
    better = sum(1 for s in pairs if (s.b_found or 0) > (s.a_found or 0))
    worse = sum(1 for s in pairs if (s.b_found or 0) < (s.a_found or 0))
    scores = [x for x in (s.sus_score for s in done) if x is not None]

    def med(attr: str) -> float | None:
        return _median([float(v) for s in done if (v := getattr(s, attr)) is not None])

    a_found, b_found = med("a_found"), med("b_found")
    if not pairs:
        found_gate = "PENDING"
    elif a_found is not None and b_found is not None and b_found > a_found and better > worse:
        found_gate = "PASS"
    else:
        found_gate = "FAIL"
    sus_mean = statistics.fmean(scores) if scores else None
    sus_gate = "PENDING" if sus_mean is None else ("PASS" if sus_mean >= SUS_TARGET else "FAIL")
    return Summary(
        n=len(done),
        ab_pairs=len(pairs),
        a_time=med("a_time"),
        b_time=med("b_time"),
        a_found=a_found,
        b_found=b_found,
        a_wrong=med("a_wrong"),
        b_wrong=med("b_wrong"),
        b_ids=med("b_ids_correct"),
        better=better,
        same=len(pairs) - better - worse,
        worse=worse,
        sus_n=len(scores),
        sus_mean=sus_mean,
        sus_sd=statistics.stdev(scores) if len(scores) > 1 else None,
        sus_median=_median(scores),
        sus_min=min(scores) if scores else None,
        sus_max=max(scores) if scores else None,
        found_gate=found_gate,
        sus_gate=sus_gate,
    )


def render(sessions: list[Session], s: Summary) -> str:
    done = [x for x in sessions if x.has_data]
    lines = [BEGIN, ""]
    if not done:
        lines += [
            "_No sessions recorded yet. Fill in `docs/usability/sessions.csv`, then run "
            "`python scripts/usability_summary.py`._",
            "",
        ]
    lines += [
        "### Round 3 gates",
        "",
        "| Gate | Target | Result | Status |",
        "|---|---|---|---|",
        f"| SUS | mean ≥ {SUS_TARGET:g} | "
        + (f"{_fmt(s.sus_mean)} (n = {s.sus_n})" if s.sus_mean is not None else "")
        + f" | {s.sus_gate} |",
        "| Seeded issues caught | Errata (B) > manual (A), more participants better than worse | "
        + (
            f"median {_fmt(s.b_found)}/4 vs {_fmt(s.a_found)}/4; better {s.better}, "
            f"same {s.same}, worse {s.worse} (n = {s.ab_pairs})"
            if s.ab_pairs
            else ""
        )
        + f" | {s.found_gate} |",
        "",
        "### A/B benchmark (medians)",
        "",
        "| Condition | Time | Found (/4) | Wrong flags | Correct rule IDs (/4) |",
        "|---|---|---|---|---|",
        f"| A: manual | {_fmt(s.a_time, ' s', 0)} | {_fmt(s.a_found)} | {_fmt(s.a_wrong)} | n/a |",
        f"| B: Errata | {_fmt(s.b_time, ' s', 0)} | {_fmt(s.b_found)} | {_fmt(s.b_wrong)} "
        f"| {_fmt(s.b_ids)} |",
        "",
        "### Per participant",
        "",
        "| Participant | Order | A time | A found | A wrong | B time | B found | B wrong | B IDs "
        "| T1 | T2 | T3 | T4 | SUS |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for x in done:
        cells = [
            x.pid,
            "A→B" if x.order == "AB" else "B→A",
            _fmt(x.a_time, " s", 0),
            "" if x.a_found is None else str(x.a_found),
            "" if x.a_wrong is None else str(x.a_wrong),
            _fmt(x.b_time, " s", 0),
            "" if x.b_found is None else str(x.b_found),
            "" if x.b_wrong is None else str(x.b_wrong),
            "" if x.b_ids_correct is None else str(x.b_ids_correct),
            *[x.tasks.get(t, "") for t in TASKS],
            _fmt(x.sus_score),
        ]
        lines.append("| " + " | ".join(cells) + " |")
    task_rows = []
    for t in TASKS:
        vals = [x.tasks[t] for x in done if t in x.tasks]
        if vals:
            task_rows.append(
                f"| {t.upper()} | {vals.count('Y')} | {vals.count('H')} | {vals.count('N')} |"
            )
    lines += [
        "",
        "### Task completion",
        "",
        "| Task | Completed | With help | Not completed |",
        "|---|---|---|---|",
        *task_rows,
    ]
    lines += [
        "",
        "### SUS",
        "",
        "| n | Mean | SD | Median | Min | Max |",
        "|---|---|---|---|---|---|",
        f"| {s.sus_n} | {_fmt(s.sus_mean)} | {_fmt(s.sus_sd)} | {_fmt(s.sus_median)} "
        f"| {_fmt(s.sus_min)} | {_fmt(s.sus_max)} |",
        "",
        END,
    ]
    return "\n".join(lines)


def splice(document: str, block: str) -> str:
    if BEGIN in document and END in document:
        head = document[: document.index(BEGIN)]
        tail = document[document.index(END) + len(END) :]
        return head + block + tail
    raise SessionError(f"{RESULTS_PATH.name} is missing the generated-block markers")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--csv", type=Path, default=CSV_PATH)
    ap.add_argument("--results", type=Path, default=RESULTS_PATH)
    ap.add_argument("--check", action="store_true", help="exit 1 if results.md is out of date")
    a = ap.parse_args(argv)
    with a.csv.open(newline="", encoding="utf-8") as fh:
        sessions = parse(list(csv.DictReader(fh)))
    summary = summarise(sessions)
    block = render(sessions, summary)
    current = a.results.read_text(encoding="utf-8")
    updated = splice(current, block)
    print(
        f"{summary.n} sessions with data; SUS {summary.sus_gate}; seeded issues {summary.found_gate}"
    )
    if a.check:
        return 0 if updated == current else 1
    a.results.write_text(updated, encoding="utf-8")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except SessionError as exc:
        print(f"error: {exc}", file=sys.stderr)
        sys.exit(2)
